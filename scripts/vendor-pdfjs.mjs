import { mkdir, copyFile, cp, readFile, writeFile } from 'node:fs/promises';
const source = new URL('../node_modules/pdfjs-dist/', import.meta.url);
const target = new URL('../frontend/vendor/pdfjs/', import.meta.url);
await mkdir(target, { recursive: true });
for (const file of ['build/pdf.min.mjs', 'build/pdf.worker.min.mjs']) await copyFile(new URL(file, source), new URL(file.split('/').at(-1), target));
for (const folder of ['cmaps', 'standard_fonts', 'wasm']) await cp(new URL(folder, source), new URL(folder, target), { recursive: true });
await copyFile(new URL('LICENSE', source), new URL('LICENSE', target));
const { version } = JSON.parse(await readFile(new URL('package.json', source), 'utf8'));
await writeFile(new URL('VERSION', target), version + '\n');
console.log('PDF.js local assets: ' + version);
